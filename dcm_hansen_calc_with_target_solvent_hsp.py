# ------------------------------------------------------------
# Target Hansen parameters
# ------------------------------------------------------------

target_hsp = np.array([17.0, 7.3, 7.1]) #Hansen (HSPiP) and Steven Abbott for DCM

# ------------------------------------------------------------
# Hansen distance
# ------------------------------------------------------------

def hansen_distance(a, b):
    dd, dp, dh = np.array(a) - np.array(b)
    return np.sqrt(4 * dd**2 + dp**2 + dh**2)

# ------------------------------------------------------------
# Miscibility check
# ------------------------------------------------------------

def are_miscible(hsp_a, hsp_b, threshold=10.0):
    return hansen_distance(hsp_a, hsp_b) <= threshold

# ------------------------------------------------------------
# 5. Binary optimization
# ------------------------------------------------------------

def best_binary_blend(hsp_a, hsp_b, target):
    hsp_a = np.array(hsp_a)
    hsp_b = np.array(hsp_b)

    def objective(phi):
        mix = phi * hsp_a + (1 - phi) * hsp_b
        return hansen_distance(mix, target)

    result = minimize_scalar(objective, bounds=(0, 1), method="bounded")
    return result.fun, result.x, 1 - result.x

# ------------------------------------------------------------
# Ternary optimization
# ------------------------------------------------------------

def best_ternary_blend(hsp_a, hsp_b, hsp_c, target):
    hsp_a = np.array(hsp_a)
    hsp_b = np.array(hsp_b)
    hsp_c = np.array(hsp_c)

    def objective(x): # x = [phi_a, phi_b]
        phi_a, phi_b = x
        if phi_a < 0 or phi_b < 0 or phi_a + phi_b > 1:
            return np.inf # Penalize invalid combinations
        phi_c = 1 - phi_a - phi_b
        mix = phi_a * hsp_a + phi_b * hsp_b + phi_c * hsp_c
        return hansen_distance(mix, target)

    # Bounds for phi_a and phi_b
    bounds = ((0, 1), (0, 1))
    # Constraint: phi_a + phi_b <= 1
    constraints = ({'type': 'ineq', 'fun': lambda x: 1 - x[0] - x[1]})

    # Initial guess for phi_a and phi_b (e.g., equal parts if valid)
    initial_guess = [1/3, 1/3]

    result = minimize(objective, initial_guess, method='SLSQP', bounds=bounds, constraints=constraints)

    if result.success:
        phi_a, phi_b = result.x
        phi_c = 1 - phi_a - phi_b
        return result.fun, phi_a, phi_b, phi_c
    else:
        return np.inf, 0, 0, 0 # Return infinity distance if optimization fails


# ------------------------------------------------------------
# Pre-filter solvents (speed boost)
# ------------------------------------------------------------

def near_target(hsp, target, cutoff=12):
    return hansen_distance(hsp, target) < cutoff

filtered = {k:v for k,v in solvents.items() if near_target(v, target_hsp)}

# ------------------------------------------------------------
# Binary search
# ------------------------------------------------------------

binary_results = []

for a, b in combinations(filtered.keys(), 2):
    if not are_miscible(filtered[a], filtered[b]):
        continue

    dist, phi_a, phi_b = best_binary_blend(filtered[a], filtered[b], target_hsp)

    binary_results.append({
        "type": "binary",
        "A": a,
        "B": b,
        "phi_A": phi_a,
        "phi_B": phi_b,
        "distance": dist
    })

# ------------------------------------------------------------
# Ternary search
# ------------------------------------------------------------

ternary_results = []

for a, b, c in combinations(filtered.keys(), 3):
    # Check miscibility of all pairs within the ternary blend
    if not (are_miscible(filtered[a], filtered[b]) and \
            are_miscible(filtered[a], filtered[c]) and \
            are_miscible(filtered[b], filtered[c])):
        continue

    dist, phi_a, phi_b, phi_c = best_ternary_blend(filtered[a], filtered[b], filtered[c], target_hsp)

    if dist < np.inf: # Only add if optimization was successful
        ternary_results.append({
            "type": "ternary",
            "A": a,
            "B": b,
            "C": c,
            "phi_A": phi_a,
            "phi_B": phi_b,
            "phi_C": phi_c,
            "distance": dist
        })

