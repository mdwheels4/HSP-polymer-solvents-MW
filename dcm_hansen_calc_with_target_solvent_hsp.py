# ------------------------------------------------------------
# Function to project HSP to 2D (corrected)
# ------------------------------------------------------------
def project_to_2d(hsp, ignore_dim="δh"):
    hsp = np.array(hsp)

    if ignore_dim == "δh":        # δd vs δp
        return hsp[0], hsp[1]
    elif ignore_dim == "δp":      # δd vs δh
        return hsp[0], hsp[2]
    elif ignore_dim == "δd":      # δp vs δh
        return hsp[1], hsp[2]

